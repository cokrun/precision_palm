const DICTIONARIES = {
    en: TRANSLATIONS_EN,
    id: TRANSLATIONS_ID
};

/**
 * Returns translation for a given key with optional fallback text.
 * @param {string} key - Dictionary lookup key
 * @param {string} [fallback] - Fallback text if key not found
 * @returns {string}
 */
function t(key, fallback = '') {
    const dict = DICTIONARIES[currentLang] || DICTIONARIES[DEFAULT_LANG];
    if (dict && dict[key] !== undefined) {
        return dict[key];
    }
    const defaultDict = DICTIONARIES[DEFAULT_LANG];
    if (defaultDict && defaultDict[key] !== undefined) {
        return defaultDict[key];
    }
    return fallback || key;
}

/**
 * Scans document for [data-i18n] and [data-i18n-placeholder] attributes and updates them.
 */
function applyTranslations() {
    const dict = DICTIONARIES[currentLang] || DICTIONARIES[DEFAULT_LANG];

    // Ensure document lang attribute is synchronized
    document.documentElement.lang = currentLang;

    // 1. Update text content for elements with data-i18n
    const textElements = document.querySelectorAll('[data-i18n]');
    textElements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict && dict[key] !== undefined) {
            el.innerHTML = dict[key];
        }
    });

    // 2. Update placeholders for input/textarea elements with data-i18n-placeholder
    const inputElements = document.querySelectorAll('[data-i18n-placeholder]');
    inputElements.forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (dict && dict[key] !== undefined) {
            el.setAttribute('placeholder', dict[key]);
        }
    });

    // 3. Update document title if applicable
    const titleKey = document.documentElement.getAttribute('data-i18n-title');
    if (titleKey && dict && dict[titleKey]) {
        document.title = dict[titleKey];
    }

    // 4. Update title/tooltip attributes for elements with [data-i18n-title]
    const titledElements = document.querySelectorAll('[data-i18n-title]');
    titledElements.forEach(el => {
        if (el === document.documentElement) return;
        const key = el.getAttribute('data-i18n-title');
        if (dict && dict[key] !== undefined) {
            el.setAttribute('title', dict[key]);
        }
    });

    // 4. Synchronize language switch button classes in header & everywhere
    syncLanguageButtonsUI();
}

/**
 * Updates visual styling of EN/ID toggles in any navbar or header.
 */
function syncLanguageButtonsUI() {
    const btnEN = document.getElementById('btnLangEN') || document.getElementById('btn_lang_en') || document.getElementById('btnMobileLangEn');
    const btnID = document.getElementById('btnLangID') || document.getElementById('btn_lang_id') || document.getElementById('btnMobileLangId');

    const activeClasses = "px-2 py-1 rounded-lg transition-all bg-emerald-600 text-white font-bold shadow-xs cursor-pointer text-[10px]";
    const inactiveClasses = "px-2 py-1 rounded-lg transition-all text-slate-500 hover:text-slate-900 dark:hover:text-white cursor-pointer font-bold text-[10px]";

    if (btnEN && btnID) {
        if (currentLang === 'id') {
            btnID.className = activeClasses;
            btnEN.className = inactiveClasses;
        } else {
            btnEN.className = activeClasses;
            btnID.className = inactiveClasses;
        }
    }

    // Synchronize topology sub-header toolbar buttons if present
    const btnTopEN = document.getElementById('btnTopLangEN');
    const btnTopID = document.getElementById('btnTopLangID');
    if (btnTopEN && btnTopID) {
        if (currentLang === 'id') {
            btnTopID.className = "px-2.5 py-1 rounded-lg transition bg-emerald-600 text-white cursor-pointer text-[10px]";
            btnTopEN.className = "px-2.5 py-1 rounded-lg transition text-slate-400 hover:text-white cursor-pointer text-[10px]";
        } else {
            btnTopEN.className = "px-2.5 py-1 rounded-lg transition bg-emerald-600 text-white cursor-pointer text-[10px]";
            btnTopID.className = "px-2.5 py-1 rounded-lg transition text-slate-400 hover:text-white cursor-pointer text-[10px]";
        }
    }
}

/**
 * Switches application language, persists choice, updates DOM, and emits custom event.
 * @param {'en'|'id'} langCode - Target language code
 */
function setAppLanguage(langCode) {
    const target = (langCode === 'id' || langCode === 'en') ? langCode : DEFAULT_LANG;
    currentLang = target;
    document.documentElement.lang = target;

    try {
        localStorage.setItem(STORAGE_LANG_KEY, target);
        // Maintain backward compatibility for all existing keys
        localStorage.setItem('precision_palm_language', target);
        localStorage.setItem('precision_palm_mobile_lang', target);
    } catch (e) {
        console.warn('[i18n] Failed to persist language in localStorage:', e);
    }

    applyTranslations();

    // Broadcast reactive event to allow Leaflet maps, reticle canvases, or charts to adapt
    window.dispatchEvent(new CustomEvent('languagechanged', {
        detail: { lang: target }
    }));
}

function getAppLanguage() {
    return currentLang;
}

document.addEventListener('DOMContentLoaded', function () {
    applyTranslations();
});

// Export to global window object
window.t = t;
window.setAppLanguage = setAppLanguage;
window.getAppLanguage = getAppLanguage;
window.applyTranslations = applyTranslations;
window.PRECISION_PALM_I18N = {
    current: () => currentLang,
    dictionaries: DICTIONARIES,
    set: setAppLanguage,
    t: t
};