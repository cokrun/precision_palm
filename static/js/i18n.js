const STORAGE_LANG_KEY = 'precision_palm_lang';
const DEFAULT_LANG = 'en';

let currentLang = (function () {
    try {
        const stored = localStorage.getItem(STORAGE_LANG_KEY) ||
            localStorage.getItem('precision_palm_language') ||
            localStorage.getItem('precision_palm_mobile_lang');
        if (stored === 'id' || stored === 'en') {
            return stored;
        }
    } catch (e) {
        console.warn('[i18n] Storage access unavailable, defaulting to English:', e);
    }
    return DEFAULT_LANG;
})();

